/**
 * Generate the TypeScript declarations natlang programs read for each Vibestudio
 * eval service (`@workspace/natlang-services`).
 *
 * The declarations are not written by hand: each service's contract (a zod
 * method table in `packages/service-schemas`, or beside its implementation in
 * the Base template) is rendered as `export function` declarations with doc
 * comments. `--check` fails when the committed file is stale, like the other
 * generated runtime catalogs (`pnpm check:runtime-docs`).
 *
 *   node scripts/generate-natlang-service-declarations.mjs [--check]
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { tsImport } from "tsx/esm/api";
import { zodToJsonSchema } from "zod-to-json-schema";
import developmentTemplateConfig from "../src/dev/developmentTemplateConfig.cjs";
import { docComment, renderMethod } from "./lib/json-schema-declarations.mjs";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = "packages/natlang-services/src/serviceDeclarations.generated.ts";

const userlandTsconfig = path.join(
  repoRoot,
  "scripts/config/userland-schema-imports.tsconfig.json"
);
const importOptions = { parentURL: import.meta.url, tsconfig: userlandTsconfig };

/** zod-to-json-schema reports JSON-value recursion on stderr; those schemas render as `unknown`. */
function toJsonSchema(schema) {
  const warn = console.warn;
  console.warn = (...args) => {
    if (typeof args[0] === "string" && args[0].startsWith("Recursive reference detected")) return;
    warn(...args);
  };
  try {
    return zodToJsonSchema(schema, { target: "openApi3", $refStrategy: "none" });
  } finally {
    console.warn = warn;
  }
}

function emptyTuple() {
  return { type: "array", minItems: 0, maxItems: 0, items: [] };
}

async function loadTable(contract, userlandRoot) {
  const file =
    contract.origin === "host"
      ? path.join(repoRoot, "packages/service-schemas/src", `${contract.module}.ts`)
      : path.join(userlandRoot, contract.file);
  const loaded = await tsImport(file, importOptions);
  const table = loaded[contract.table];
  if (!table || typeof table !== "object") {
    throw new Error(`${contract.table} is not exported from ${path.relative(repoRoot, file)}`);
  }
  return table;
}

function renderService(entry, table) {
  const declarations = entry.methods.map((method) => {
    const contractName = method.contractMethod ?? method.name;
    const contract = table[contractName];
    if (!contract)
      throw new Error(`${entry.name}.${method.name}: no contract entry ${contractName}`);
    const returns = contract.returns ?? contract.result;
    const description = contract.description ?? method.description;
    if (!description)
      throw new Error(`${entry.name}.${method.name}: the contract has no description`);
    return renderMethod({
      name: method.name,
      description,
      argsSchema: contract.args ? toJsonSchema(contract.args) : emptyTuple(),
      returnsSchema: returns ? toJsonSchema(returns) : undefined,
      params: method.params,
      argsArm: method.argsArm,
      bound: method.bound,
    });
  });
  return `${docComment(entry.summary)}\n\n${declarations.join("\n\n")}`;
}

/** Render every service's declaration, keyed by service name. */
export async function renderServiceDeclarations(userlandRoot) {
  const { SERVICE_CATALOG } = await tsImport(
    path.join(userlandRoot, "packages/natlang-services/src/catalog.ts"),
    importOptions
  );
  const declarations = {};
  for (const entry of SERVICE_CATALOG) {
    declarations[entry.name] = renderService(entry, await loadTable(entry.contract, userlandRoot));
  }
  return declarations;
}

function templateLiteral(text) {
  return `\`${text.replaceAll("\\", "\\\\").replaceAll("`", "\\`").replaceAll("${", "\\${")}\``;
}

/** The generated module's source text. */
export function renderModule(declarations) {
  const entries = Object.entries(declarations).map(
    ([name, text]) => `  ${name}: ${templateLiteral(text)},`
  );
  return [
    "// Generated by scripts/generate-natlang-service-declarations.mjs in the Vibestudio host.",
    "// Do not edit. Regenerate with: node scripts/generate-natlang-service-declarations.mjs",
    "",
    "/**",
    " * The declaration text of each service: the members of `declare namespace <name> { ... }`,",
    " * rendered from the service contracts named in `catalog.ts`.",
    " */",
    "export const generatedServiceDeclarations: Readonly<Record<string, string>> = {",
    ...entries,
    "};",
    "",
  ].join("\n");
}

export async function generate({ checkOnly = false } = {}) {
  const userlandRoot = developmentTemplateConfig.requireDevelopmentTemplateCheckout(
    repoRoot,
    "base"
  );
  const next = renderModule(await renderServiceDeclarations(userlandRoot));
  const target = path.join(userlandRoot, OUTPUT);
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : null;
  if (checkOnly) {
    if (next !== current) {
      throw new Error(
        `${OUTPUT} in the Base template is out of date. Run: node scripts/generate-natlang-service-declarations.mjs`
      );
    }
    return next;
  }
  if (next !== current) fs.writeFileSync(target, next);
  return next;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await generate({ checkOnly: process.argv.includes("--check") });
}
